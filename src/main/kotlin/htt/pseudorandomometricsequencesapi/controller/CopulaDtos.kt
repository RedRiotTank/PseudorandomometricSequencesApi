package htt.pseudorandomometricsequencesapi.controller

import io.swagger.v3.oas.annotations.media.ArraySchema
import io.swagger.v3.oas.annotations.media.Schema

@Schema(
    description = "Request for generating statistically dependent variables with a Gaussian copula. " +
        "Each variable may use any registered univariate distribution."
)
data class CopulaRequest(
    @get:Schema(
        description = "Number of samples to generate for each variable. Must be positive.",
        example = "1000"
    )
    val count: Int = 10,

    @get:Schema(
        description = "The base generator type.",
        allowableValues = ["general", "secure"],
        example = "general"
    )
    val type: String = "general",

    @get:Schema(
        description = "Seed used to reproduce the dependent sequences.",
        example = "42"
    )
    val seed: Long? = null,

    @get:Schema(
        description = "Symmetric positive-definite correlation matrix. Diagonal entries must be 1.0. " +
            "Controls rank dependence between variables.",
        example = "[[1.0, 0.8], [0.8, 1.0]]"
    )
    val correlation: List<List<Double>>,

    @get:Schema(
        description = "Marginal variables to generate. The number of variables must match the correlation " +
            "matrix dimension.",
        requiredMode = Schema.RequiredMode.REQUIRED
    )
    val variables: List<CopulaVariableRequest> = emptyList(),

    @get:Schema(
        description = "Number of samples used to build each empirical marginal quantile table. " +
            "Larger values improve tail accuracy at the cost of more computation.",
        example = "100000"
    )
    val quantileSamples: Int = 100_000
)

@Schema(description = "Definition of one marginal variable for a Gaussian-copula request.")
data class CopulaVariableRequest(
    @get:Schema(
        description = "Optional unique name. Defaults to 'variable1', 'variable2', ... in request order.",
        example = "temperature"
    )
    val name: String? = null,

    @get:Schema(
        description = "Any registered univariate distribution, e.g. gaussian, gamma, beta, poisson, binomial.",
        example = "gaussian"
    )
    val distribution: String,

    @get:Schema(
        description = "First parameter of the distribution (meaning depends on the distribution).",
        example = "0.0"
    )
    val param1: Double? = null,

    @get:Schema(
        description = "Second parameter of the distribution (meaning depends on the distribution).",
        example = "1.0"
    )
    val param2: Double? = null,

    @get:Schema(
        description = "Third parameter of the distribution (meaning depends on the distribution).",
        example = "1.0"
    )
    val param3: Double? = null
)

@Schema(description = "Statistically dependent sequences generated by a Gaussian copula.")
data class CopulaResponse(
    @get:Schema(
        description = "The type of random number generator used.",
        allowableValues = ["secure", "general"],
        example = "general"
    )
    val type: String,

    @get:Schema(description = "The number of samples generated for each variable.")
    val count: Int,

    @get:Schema(description = "The dependence model used.", example = "gaussian")
    val copula: String,

    @get:Schema(
        description = "How marginal inverse CDFs were obtained.",
        example = "empirical-quantile"
    )
    val marginalMethod: String,

    @get:Schema(description = "The seed used to generate the sequences.", example = "42")
    val seed: Long,

    @get:Schema(
        description = "Number of samples used to build each empirical marginal quantile table.",
        example = "100000"
    )
    val quantileSamples: Int,

    @get:Schema(description = "The correlation matrix used by the copula.")
    val correlation: List<List<Double>>,

    @get:ArraySchema(
        arraySchema = Schema(description = "One dependent sequence per marginal variable."),
        schema = Schema(implementation = CopulaVariableResponse::class)
    )
    val variables: List<CopulaVariableResponse>
)

@Schema(description = "A statistically dependent sequence for one marginal variable.")
data class CopulaVariableResponse(
    @get:Schema(description = "The resolved variable name.", example = "temperature")
    val name: String,

    @get:Schema(description = "The marginal distribution used.", example = "gaussian")
    val distribution: String,

    @get:ArraySchema(
        arraySchema = Schema(description = "The list of generated values."),
        schema = Schema(implementation = Double::class)
    )
    val sequence: List<Double>
)
